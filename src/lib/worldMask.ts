let bits: Uint8Array | null = null;

function decode() {
  const binary = atob(PACKED);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}

/** True where the given point (degrees) falls on land. */
export function isLand(latDeg: number, lonDeg: number) {
  if (!bits) bits = decode();
  let col = Math.floor(((lonDeg + 180) / 360) * MASK_W);
  let row = Math.floor(((90 - latDeg) / 180) * MASK_H);
  if (col < 0) col += MASK_W;
  if (col >= MASK_W) col -= MASK_W;
  if (row < 0) row = 0;
  if (row >= MASK_H) row = MASK_H - 1;
  const index = row * MASK_W + col;
  return (bits[index >> 3] & (128 >> (index & 7))) !== 0;
}
