/* ============================================================================
   World mask — a 192x96 land/ocean bitmap in equirectangular lat/lon.

   Derived from the brand plate (public/images/world-network.png) by inverting
   its Mercator projection and thresholding luminance, so the continents the
   hero globe draws are the same ones the mark is built on. 2.3kb packed, one
   bit per cell, decoded once on first use.

   Regenerated only if the brand plate changes; the source projection is
   Mercator cropped to roughly +78..-56 latitude, which is why the poles read
   as ocean here — no dot is ever placed on them.
   ========================================================================== */

